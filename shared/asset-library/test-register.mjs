import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {syncCatalog,inspectFile,buildEntry} from './register-parts.mjs';
import {validateCatalog,rankAsset} from './prepare.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'register-parts-'));
const folder=path.join(root,'パーツ'),catalogPath=path.join(root,'catalog.json');
const fixture={version:2,threshold:0.88,policy:{visualStyle:'cinematic-vector',palette:'muted-dark'},assets:[]};
const write=(name,color)=>fs.writeFileSync(path.join(folder,name),'<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400"><rect width="400" height="400" fill="'+color+'"/></svg>');
const metadata={name:'砂時計',description:'砂が落ちる砂時計',tags:['砂時計','時間','砂'],mustMentionAny:['砂時計'],avoid:[],style:'cinematic-vector',palette:'muted-dark'};
let calls=0;
const analyze=async()=>{calls++;return metadata;};
const read=()=>JSON.parse(fs.readFileSync(catalogPath,'utf8'));
try{
 fs.mkdirSync(folder);fs.writeFileSync(catalogPath,JSON.stringify(fixture,null,2)+'\n');
 write('hourglass.svg','#123456');
 assert.equal((await syncCatalog({root,analyze})).registered,1);
 assert.equal(calls,1);
 let entry=read().assets[0];
 assert.equal(entry.file,'パーツ/hourglass.svg');
 assert.equal(entry.phases[0],'*');
 assert.equal(entry.license,'pending-review');
 validateCatalog(read(),root);
 assert.equal(rankAsset(entry,{phase:'some-new-film-phase',narration:'砂時計の砂で時間を説明'},{visualStyle:'cinematic-vector',palette:'muted-dark',threshold:0.88}),null,'unverified rights block automatic selection');
 const unchanged=fs.readFileSync(catalogPath,'utf8');
 assert.equal((await syncCatalog({root,analyze})).registered,0,'unchanged images never call the API');
 assert.equal(fs.readFileSync(catalogPath,'utf8'),unchanged,'idempotent catalog');
 assert.equal(calls,1);
 entry.license='original-project';
 const approved=read();approved.assets[0]=entry;
 fs.writeFileSync(catalogPath,JSON.stringify(approved,null,2)+'\n');
 assert(rankAsset(entry,{phase:'brand_new_phase',narration:'砂時計の砂で時間を説明'},{visualStyle:'cinematic-vector',palette:'muted-dark',threshold:0.88}));
 write('hourglass.svg','#654321');
 await syncCatalog({root,analyze});
 assert.equal(calls,2);
 assert.equal(read().assets[0].id,entry.id,'stable ID when image content is replaced');
 assert.equal(read().assets[0].license,'original-project','preserve reviewed rights on replacement');
 write('second.svg','#aaaaaa');
 const before=fs.readFileSync(catalogPath,'utf8');
 await assert.rejects(()=>syncCatalog({root,analyze:async()=>({tags:['砂時計'],mustMentionAny:['砂時計'],avoid:[],style:'other',palette:'colorful'})}),/Invalid AI metadata/);
 assert.equal(fs.readFileSync(catalogPath,'utf8'),before,'never partially write a failing auto-registration');
 await syncCatalog({root,analyze});
 assert.equal(read().assets.length,2);
 fs.rmSync(path.join(folder,'second.svg'));
 await syncCatalog({root,analyze});
 assert.equal(read().assets.length,1,'deleted auto asset removed from master');
 const unsafe=path.join(folder,'bad.svg');
 fs.writeFileSync(unsafe,'<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>');
 assert.throws(()=>inspectFile(unsafe),/Unsafe SVG/);
 assert.throws(()=>buildEntry({file:'パーツ/unsafe.svg',sha256:'a',metadata:{...metadata,tags:['時間']}}),/Invalid AI metadata/);
 console.log('Auto-registration: initial scan, no-op, replacement, rights gate, wildcard, rollback, deletion, safety PASS');
}finally{fs.rmSync(root,{recursive:true,force:true});}
