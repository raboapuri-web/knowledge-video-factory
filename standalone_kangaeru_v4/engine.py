#!/usr/bin/env python3
"""End-to-end pipeline orchestrator, with fail-closed licensing and QA."""
import argparse, hashlib, json, math, subprocess, sys, wave
from pathlib import Path
import core
import render

def stamp(t):
 m=int(t//60);s=int(t%60);ms=int((t-int(t))*1000)
 return f"00:{m:02d}:{s:02d},{ms:03d}"

def subtitles_srt(timeline):
 result=[];idx=0
 for s in timeline:
  for p in s["subtitles"]:
   idx+=1
   result += [str(idx),stamp(p["start"])+" --> "+stamp(p["end"]),p["text"],""]
 return "\n".join(result)

def qa(board,timeline,materials,final,stage):
 checks={}
 def check(k,condition,message=""):
  checks[k]={"passed":bool(condition),"message":message}
 check("caption_alignment",board["art_direction"]["subtitle_alignment"]=="center",
  "horizontal center x=640; 1- or 2-line text drawn using Pillow anchor=mm")
 check("subtitle_zone",board["art_direction"]["subtitle_zone"]==[0,586,1280,134],
  "subtitle band y>=586, visual elements restricted to the upper region")
 check("subtitle_text",all(p["text"].strip() and 1<=len(p["text"].splitlines())<=2
      for s in timeline for p in s["subtitles"]),"no clipping/ellipsis; at most two lines per page")
 check("timeline",len(timeline)==len(board["scenes"]) and all(timeline[i]["start"]<timeline[i]["end"] and
      (i==0 or abs(timeline[i]["start"]-timeline[i-1]["end"])<.005) for i in range(len(timeline))))
 check("sound_real_tts",all(s["wav_duration"]>.3 and Path(s["wav"]).exists()
      for s in timeline),"each scene WAV is generated by a real TTS engine")
 check("assets_cc0",bool(materials) and all(a["license"]=="CC0" and a.get("source_page","").startswith("https://commons.wikimedia.org/wiki/File:")
      and hashlib.sha256(Path(a["file"]).read_bytes()).hexdigest()==a["sha256"] for a in materials),
      "each fetched file verified on its individual Commons item metadata")
 check("assets_used",all(s["photo"] in {a["id"] for a in materials}
      for s in board["scenes"] if s["style"] in ("photo","evidence")))
 check("icon_registry",len(core.ICON_NAMES)==24 and len(set(core.ICON_NAMES))==24)
 check("storyboard_diversity",len({s["style"] for s in board["scenes"]})>=5 and all(
      not (board["scenes"][i]["style"]==board["scenes"][i+1]["style"]==board["scenes"][i+2]["style"])
      for i in range(max(0,len(board["scenes"])-2))),"5+ styles; no 3 identical in a row")
 check("text_overflow",all(len(s.get("claim",""))<70 for s in board["scenes"]),
       "text preflight, renderer uses fit-to-available-width with no truncation")
 try:
  proc=subprocess.run(["ffprobe","-v","error","-show_entries","format=duration:stream=codec_type,width,height",
    "-of","json",str(final)],capture_output=True,text=True,check=True)
  info=json.loads(proc.stdout)
  kinds={s.get("codec_type") for s in info["streams"]}
  video=next((s for s in info["streams"] if s["codec_type"]=="video"),{})
  duration=float(info["format"]["duration"])
  check("streams",{"video","audio"}<=kinds and video.get("width")==1280 and video.get("height")==720,
        "H264/AAC MP4 with 1280x720 frame")
  check("duration",abs(duration-timeline[-1]["end"])<.6,f"video={duration:.2f}, timeline={timeline[-1]['end']:.2f}")
 except Exception as e:check("streams",False,str(e));check("duration",False,str(e))
 result={"passed":all(x["passed"] for x in checks.values()),"checks":checks,
  "scene_count":len(board["scenes"]),"duration_seconds":timeline[-1]["end"],"final_mp4":str(final),
  "note":"Mechanized checks do not certify subjective visual beauty or scientific claims."}
 (stage/"qa.json").write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding="utf8")
 return result

def main():
 p=argparse.ArgumentParser()
 p.add_argument("--script",type=Path,required=True)
 p.add_argument("--output",type=Path,required=True)
 p.add_argument("--voicevox-url",default="")
 p.add_argument("--no-render",action="store_true")
 args=p.parse_args()
 out=args.output.resolve();out.mkdir(parents=True,exist_ok=True)
 data=json.loads(args.script.read_text(encoding="utf8"))
 board=core.make_storyboard(data)
 (out/"storyboard.json").write_text(json.dumps(board,indent=2,ensure_ascii=False),encoding="utf8")
 materials=core.acquire_all(board,out)
 timeline=core.make_timeline(board,out,args.voicevox_url)
 (out/"timeline.json").write_text(json.dumps(timeline,indent=2,ensure_ascii=False),encoding="utf8")
 (out/"captions.srt").write_text(subtitles_srt(timeline),encoding="utf8")
 (out/"icon_registry.json").write_text(json.dumps(core.ICON_NAMES,ensure_ascii=False,indent=2),encoding="utf8")
 # Create all 24 icon PNGs; users may later replace them by the original uploaded asset atlas.
 iconfolder=out/"icons";iconfolder.mkdir(exist_ok=True)
 for n in core.ICON_NAMES:core.icon_image(n).save(iconfolder/(n+".png"))
 description="なぜ植物は緑なのか？\n\n葉の色から、当たり前を問い直す短い映像試作。\n\n"
 description+="写真素材（CC0／出典）\n"
 for x in materials:description+="- "+x["subject"]+" / "+x["author"]+": "+x["source_page"]+"\n"
 description+="\nナレーション: espeak-ng (開発用仮音声。公開音声としての使用を推奨しません)\n"
 (out/"description.md").write_text(description,encoding="utf8")
 if args.no_render:return
 final=render.render(board,timeline,{m["id"]:m for m in materials},out)
 report=qa(board,timeline,materials,final,out)
 print(json.dumps({"passed":report["passed"],"file":str(final),
     "duration":report["duration_seconds"],"checks":report["checks"]},ensure_ascii=False,indent=2))
 if not report["passed"]:raise SystemExit("QA FAILED")

if __name__=="__main__":main()
